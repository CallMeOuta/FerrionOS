#!/usr/bin/env python3
"""Generate the DD2 compositor configs from the checked-in desktop fixtures."""
import argparse
from pathlib import Path
from desktop_fixtures import load_regions

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / 'recipes/wip/wayland/ferrion-wm'


def config(radius):
    regions = load_regions('desktop-tiling.svg')
    files = regions['region-window-files']['rect']
    editor = regions['region-window-editor']['rect']
    gap = int(editor[0] - files[0] - files[2])
    text = f'''// Generated by scripts/ferrion-wm-config.py from desktop-tiling.svg.
// FerrionOS DD2 test session; the default desktop is configured separately.
input {{
    keyboard {{ xkb {{ layout "us"; }}; }}
}}
output "ferrion-1" {{ scale 1; }}
layout {{
    gaps {gap}
    center-focused-column "never"
    focus-ring {{ off; }}
    border {{
        on
        width 1
        active-color "#7e7c7a"
        inactive-color "#2e2d2b"
    }}
    shadow {{ off; }}
    background-color "#0f0e0c"
    struts {{ top {int(files[1]) - gap}; }}
}}
animations {{ off; }}
hotkey-overlay {{ skip-at-startup; }}
prefer-no-csd
xwayland-satellite {{ off; }}
window-rule {{
    geometry-corner-radius {radius}
    clip-to-geometry true
}}
'''
    for role in ('files', 'editor', 'terminal'):
        width = int(regions[f'region-window-{role}']['rect'][2]) - 2
        text += f'''window-rule {{
    match app-id="^ferrion-desktop-{role}$"
    default-column-width {{ fixed {width}; }}
}}
'''
    return text + '''binds {
    Mod+Shift+Space { toggle-window-floating; }
    Mod+Q { close-window; }
    Mod+Shift+E { quit skip-confirmation=true; }
}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, radius in [('config.kdl', 0), ('rounded.kdl', 14)]:
        path = DEST / name
        content = config(radius)
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, f'{path.relative_to(ROOT)} needs regeneration\n')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
